import { build } from "esbuild";
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const vendor = join(root, "public", "vendor");
const marker = join(vendor, "README.generated.txt");
const ownership = "Generated by Vitosha Peak Explorer prepare_assets.mjs.\n";

// This is the only directory this generator may replace, never the workspace.
if (resolve(vendor) !== resolve(root, "public", "vendor")) throw new Error("Unsafe asset output path");
try {
  if (await readFile(marker, "utf8") !== ownership) throw new Error("Unrecognized vendor directory; refusing to overwrite it");
} catch (error) {
  if (error.code !== "ENOENT") throw error;
  try {
    await stat(vendor);
    throw new Error("Existing vendor directory has no ownership marker");
  } catch (existing) { if (existing.code !== "ENOENT") throw existing; }
}
await rm(vendor, { recursive: true, force: true });
await mkdir(vendor, { recursive: true });
await writeFile(marker, ownership);
await cp(join(root, "node_modules", "cesium", "Build", "Cesium"), join(vendor, "cesium"), { recursive: true });
await cp(join(root, "node_modules", "cesium", "LICENSE.md"), join(vendor, "cesium", "LICENSE.md"));
await build({
  absWorkingDir: root,
  entryPoints: [join(root, "src", "cesium-runtime.js")],
  outfile: join(vendor, "cesium", "Cesium.js"),
  bundle: true, format: "iife", globalName: "Cesium", platform: "browser",
  target: "es2022", minify: true, legalComments: "linked",
  define: { "process.env.NODE_ENV": '"production"' },
});
await mkdir(join(vendor, "fonts"), { recursive: true });
for (const subset of ["latin", "cyrillic"]) {
  const file = `manrope-${subset}-wght-normal.woff2`;
  await cp(join(root, "node_modules", "@fontsource-variable", "manrope", "files", file), join(vendor, "fonts", file));
}
await cp(join(root, "node_modules", "@fontsource-variable", "manrope", "LICENSE"), join(vendor, "fonts", "LICENSE"));
await cp(join(root, "src", "fonts.css"), join(vendor, "fonts", "fonts.css"));
await mkdir(join(vendor, "licenses"), { recursive: true });
for (const name of ["react", "react-dom", "htm", "lucide-react"]) {
  const packageDir = join(root, "node_modules", name);
  const license = (await readdir(packageDir)).find(file => /^LICENSE(?:\..*)?$/i.test(file));
  if (!license) throw new Error(`Missing upstream license for ${name}`);
  await cp(join(packageDir, license), join(vendor, "licenses", `${name}.txt`));
}
await build({
  absWorkingDir: root,
  entryPoints: {
    react: join(root, "src/browser-react.js"),
    "react-dom-client": join(root, "src/browser-react-dom.js"),
    htm: join(root, "node_modules/htm/dist/htm.module.js"),
    icons: join(root, "src/icons.js"),
  },
  outdir: join(vendor, "modules"),
  bundle: true, splitting: true, format: "esm", platform: "browser", target: "es2022", minify: true,
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "linked",
});
console.log("Prepared local Cesium engine, fonts and browser-ESM modules.");
